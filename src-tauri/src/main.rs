use commands::player_commands;
use souchy_tauri_specta::Builder;
use std::{path::PathBuf, process::Command, str::FromStr};
use tauri::Manager;
use yt_dlp::client::Libraries;
use yt_dlp::Downloader;

mod commands;
mod services;

fn main() {
    dotenv::dotenv().ok();

    let specta_builder = build_specta();

    tauri::Builder::default()
        .plugin(tauri_plugin_shell::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        .invoke_handler(specta_builder.invoke_handler())
        .setup(move |app: &mut tauri::App| {
            specta_builder.mount_events(app);

            // 1. Get an absolute, safe path (e.g., App Data Directory)
            let app_dir = app.path().app_local_data_dir()?;
            // .map_err(|e| tauri::Error::Runtime(e.into()))?;

            // let yt_dlp_bin_dir = app_dir.join("libs/yt-dlp");
            // let ffmpeg_bin_dir = app_dir.join("libs/ffmpeg");
            let cache_output_dir = app_dir.join("cache_output");
            let libs_dir = app_dir.join("libs");

            std::fs::create_dir_all(&libs_dir)?;
            std::fs::create_dir_all(&cache_output_dir)?;

            // let libraries = Libraries::new(yt_dlp_bin_dir, ffmpeg_bin_dir);
            let downloader = tauri::async_runtime::block_on(async {
                // Downloader::builder(libraries, cache_output_dir)
                //     .build()
                //     .await
                Downloader::with_new_binaries(libs_dir, cache_output_dir)
                    .await?
                    .build()
                    .await
            })?;
            app.manage(downloader);

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

fn build_specta() -> souchy_tauri_specta::Builder {
    let specta_builder =
        Builder::<tauri::Wry>::new().commands(souchy_tauri_specta::collect_commands![
            player_commands::load_and_play_file,
            player_commands::pause,
            player_commands::resume,
            player_commands::stop,
            commands::yt::dl_yt,
            commands::yt::yt_search,
            commands::yt::get_video_recommendations,
            player_commands::set_volume,
            commands::library_commands::scan_folder,
            commands::library_commands::get_metadata,
            commands::library_commands::get_file_info,
            player_commands::seek,
            player_commands::get_position,
            player_commands::get_duration,
            player_commands::get_playback_status,
            commands::fs_commands::list_directories,
            commands::fs_commands::get_folder_locations,
            commands::fs_commands::get_default_download_dir,
            commands::fs_commands::create_directory,
            commands::fs_commands::reveal_in_folder,
        ]);

    specta_builder
}

